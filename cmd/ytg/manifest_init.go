// ManifestInitOptions encapsulates user choices for manifest generation.
type ManifestInitOptions struct {
	OutputPath string
	AppType    string // generic, golang, python
	Minimal    bool
	Force      bool
	ToStdout   bool
}

// GenerateManifestTemplate produces best-practice declarative manifest YAML string.
func GenerateManifestTemplate(opts ManifestInitOptions) (string, error) {
	appType := strings.ToLower(strings.TrimSpace(opts.AppType))
	if appType == "" {
		appType = "generic"
	}

	if opts.Minimal {
		return generateMinimalTemplate(appType), nil
	}

	switch appType {
	case "golang", "go":
		return generateGolangTemplate(), nil
	case "python", "py":
		return generatePythonTemplate(), nil
	case "generic":
		return generateGenericTemplate(), nil
	default:
		return "", fmt.Errorf("unsupported manifest type '%s' (valid: generic, golang, python)", opts.AppType)
	}
}

