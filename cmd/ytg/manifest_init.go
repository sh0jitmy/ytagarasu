func generateMinimalTemplate(appType string) string {
	bin := "./app"
	if appType == "python" || appType == "py" {
		bin = "python3"
	}
	return fmt.Sprintf(`version: "1.0"
processes:
  - name: main-service
    binary: %s
    auto_restart: true
`, bin)
}

func parseManifestInitArgs(args []string) (ManifestInitOptions, error) {
	opts := ManifestInitOptions{
		OutputPath: "manifest.yaml",
		AppType:    "generic",
	}

	for i := 0; i < len(args); i++ {
		arg := args[i]
		switch arg {
		case "-o", "--output":
			if i+1 >= len(args) {
				return opts, errors.New("missing argument for output path flag")
			}
			opts.OutputPath = args[i+1] //nolint:gosec // Bounds checked above
			i++
		case "--type", "-t":
			if i+1 >= len(args) {
				return opts, errors.New("missing argument for type flag")
			}
			opts.AppType = args[i+1] //nolint:gosec // Bounds checked above
			i++
		case "--minimal":
			opts.Minimal = true
		case "-f", "--force":
			opts.Force = true
		case "--stdout", "-":
			opts.ToStdout = true
		case "-h", "--help":
			printManifestInitHelp()
			os.Exit(0)
		default:
			return opts, fmt.Errorf("unknown flag for manifest init: %s", arg)
		}
	}

	if opts.OutputPath == "-" {
		opts.ToStdout = true
	}

	return opts, nil
}

func handleManifestInit(args []string) {
	opts, err := parseManifestInitArgs(args)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[ytg manifest init error] %v\n\n", err)
		printManifestInitHelp()
		os.Exit(1)
	}

	yamlContent, err := GenerateManifestTemplate(opts)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[ytg manifest init error] %v\n", err)
		os.Exit(1)
	}

	// Verify syntax using yaml parser
	var validationNode yaml.Node
	if err := yaml.Unmarshal([]byte(yamlContent), &validationNode); err != nil {
		fmt.Fprintf(os.Stderr, "[ytg manifest init error] internal template validation failed: %v\n", err)
		os.Exit(1)
	}

	if opts.ToStdout {
		fmt.Print(yamlContent)
		return
	}

	cleanOutput := filepath.Clean(opts.OutputPath)

	// Check if file exists and prevent overwrite unless --force is specified
	if !opts.Force {
		if _, err := os.Stat(cleanOutput); err == nil {
			fmt.Fprintf(os.Stderr, "[ytg manifest init error] %s already exists. Use --force to overwrite.\n", cleanOutput)
			os.Exit(1)
		}
	}

	dir := filepath.Dir(cleanOutput)
	if dir != "." && dir != "" {
		_ = os.MkdirAll(dir, 0750)
	}

	if err := os.WriteFile(cleanOutput, []byte(yamlContent), 0600); err != nil { //nolint:gosec // User-specified output path
		fmt.Fprintf(os.Stderr, "[ytg manifest init error] failed to write manifest: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("[ytg manifest init] Successfully created declarative manifest: %s (type: %s)\n", cleanOutput, opts.AppType)
	fmt.Println()
	fmt.Println("Next steps for air-gapped process management:")
	fmt.Printf("  1. Review and adjust commands: %s\n", cleanOutput)
	fmt.Printf("  2. Start supervisor daemon:   ytg supervisor run -c %s\n", cleanOutput)
	fmt.Println("  3. Inspect live telemetry:    ytg status")
}

func printManifestInitHelp() {
	printManifestInitHelpTo(os.Stdout)
}

func printManifestInitHelpTo(w io.Writer) {
	_, _ = fmt.Fprintln(w, "Usage: ytg manifest init [options]")
	_, _ = fmt.Fprintln(w)
	_, _ = fmt.Fprintln(w, "Initialize a declarative process orchestration manifest with best practices.")
	_, _ = fmt.Fprintln(w)
	_, _ = fmt.Fprintln(w, "Options:")
	_, _ = fmt.Fprintln(w, "  -o, --output <path>    Output file path (default: manifest.yaml, '-' for stdout)")
	_, _ = fmt.Fprintln(w, "  -t, --type <type>      Application type preset: generic, golang, python (default: generic)")
	_, _ = fmt.Fprintln(w, "      --minimal          Generate compact minimal skeleton without comments")
	_, _ = fmt.Fprintln(w, "  -f, --force            Overwrite existing file if present")
	_, _ = fmt.Fprintln(w, "      --stdout           Print manifest template directly to stdout")
	_, _ = fmt.Fprintln(w, "  -h, --help             Show this help message")
}
